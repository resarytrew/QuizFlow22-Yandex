
export type DocBlockType = 'text' | 'heading' | 'subheading' | 'code' | 'image' | 'alert' | 'list' | 'video';

export interface DocBlock {
    type: DocBlockType;
    content: string | string[];
    language?: string; // For code
    variant?: 'info' | 'warning' | 'success' | 'danger'; // For alerts
    caption?: string; // For images
    url?: string; // For images/video
}

export interface DocPage {
    id: string;
    title: string;
    description: string;
    blocks: DocBlock[];
}

export interface DocCategory {
    id: string;
    title: string;
    pages: DocPage[];
}

